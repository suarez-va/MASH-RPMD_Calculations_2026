"""
iterate.py -- drive the stages of MASH-RPMD_Tully-Testing (see config.py for the idea, resample.py for
the math).  Every stage lives in its own directory next to config.py:

    stage_<m>/config.py     GENERATED: inherits ../config.py, fixes stage, t_start, n_traj, base_seed
    stage_<m>/init.npz      the stage's initial points: q, p (n,), w (n, 4) = (w_I, w_z, w_x, w_y)
    stage_<m>/shards/       the stage's trajectories (workflow.shards), run by workflow.runner/slurm
    stage_<m>/summary.npz   written by `resample`: the stage's observables at every print time, the
                            endpoint totals, and the diagnostics of the resampling into stage m+1

Commands (all take --config, default config.py in the cwd):

    python iterate.py init                      # stage_00 from rho_init
    python iterate.py resample --stage m        # stage_m's trajectories -> summary + stage_(m+1)
    python iterate.py local --ncores 14         # init + every stage: run, resample (resumable)
    python iterate.py chain [--stage m]         # the same on SLURM: stage m's array, then a
                                                #   dependent job that resamples and chains m+1
    python iterate.py status                    # which stages exist / are complete / resampled

`local` and `chain` pick up where they stopped: a stage's shards skip trajectories already
committed, and a stage that is complete and resampled is passed over.  Rerunning `chain --stage m`
after a timed-out or failed array resubmits it (finished trajectories are skipped) and the
resample behind it.

Observables (summary.npz `names`), at every print time t of the stage, integrated over (q,p):

    Rg, Tg, Re, Te   int h(-+q) <g|rho|g> and int h(-+q) <e|rho|e>   (rho_I -+ rho_z, R/T = q </> 0)
    Pg, Pe, Tr       Rg+Tg, Re+Te, Pg+Pe = Tr rho
    X, Y             int rho_x, int rho_y

i.e. per trajectory a_P h(-+S_z(t)) h(-+q(t)) / n_spin and a_C S_x,y(t) / (2 n_spin), the bead factor
taken bead by bead and averaged as in analyze_tully.py.  The stage's first row (t = t_start, spins
still S^(0)) is the zero-time map: on average it equals the stage's init totals, printed next to it.
With the 1/2 convention, Rg..Te continue analyze_tully.py's C_Rg..C_Te for a Tully-Delta run with
jump_index at the stage boundaries.  SEs are across the stage's points (each point's trajectories
summed), i.e. the sampling error of that stage alone given its initial points.
"""

import os
import sys
import glob
import argparse
import subprocess
import importlib.util

import numpy as np
import h5py

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import resample as rs   # noqa: E402


NAMES = ('Rg', 'Tg', 'Re', 'Te', 'Pg', 'Pe', 'Tr', 'X', 'Y')


# ------------------------------------------------------------------ config / layout
def _load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, os.path.abspath(path))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def load_config(path):
    return _load_module(path, '_tt_config').CONFIG


def stage_dir(run_dir, m):
    return os.path.join(run_dir, f'stage_{m:02d}')


def stage_seed(base_seed, m, salt):
    """Seed of stage m: salt 0 -> its trajectories' base_seed, salt 1 -> the draw of its points."""
    if base_seed is None:
        return None
    return int(np.random.SeedSequence([int(base_seed), int(m), int(salt)]).generate_state(1)[0])


def _shard_files(sd, cfg):
    return sorted(glob.glob(os.path.join(sd, cfg.get('shard_dir', 'shards'), 'shard_*.hdf')))


def _committed(sd, cfg):
    """Every committed trajectory index of a stage (with repeats, if any)."""
    out = []
    for fn in _shard_files(sd, cfg):
        with h5py.File(fn, 'r') as f:
            if 'traj_index' in f:
                out.append(f['traj_index'][:])
    return np.concatenate(out) if out else np.zeros(0, dtype=np.int64)


def _complete(sd, scfg):
    idx = _committed(sd, scfg)
    return idx.size == int(scfg['n_traj']) and np.unique(idx).size == idx.size


_STAGE_CONFIG = '''"""
{name}/config.py -- GENERATED by iterate.py for stage {m} of MASH-RPMD_Tully-Testing.  Do not edit:
everything else is inherited from ../{base}; the keys below were fixed when the stage was created.
"""

import os
import copy
import importlib.util


def _inherit(relpath):
    """Load the parent config's CONFIG from a path relative to THIS file."""
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), relpath)
    spec = importlib.util.spec_from_file_location('_tt_base_config', p)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return copy.deepcopy(mod.CONFIG)


CONFIG = _inherit('../{base}')

CONFIG.update({{
    'stage'      : {m},
    't_start'    : {t_start!r},
    'n_traj'     : {n_traj},          # {n_pts} points x {n_spin} spins
    'base_seed'  : {seed!r},
    'system_file': '../traj.py',
    'init_file'  : 'init.npz',
}})
'''


def write_stage(config_path, cfg, m, q, p, w, info):
    """Create stage_<m>/ (config.py + init.npz). Refuses to touch a stage that already has shards."""
    run_dir = os.path.dirname(os.path.abspath(config_path))
    sd = stage_dir(run_dir, m)
    if _shard_files(sd, cfg):
        raise FileExistsError(f'{sd} already has trajectories; delete its shards to recreate it')
    os.makedirs(sd, exist_ok=True)
    n_spin = int(cfg['n_spin'])
    t_start = float(m * float(cfg['seg_time']))
    np.savez(os.path.join(sd, 'init.npz'), q=q, p=p, w=w, n_spin=n_spin, stage=m, t_start=t_start,
             **{f'resample_{k}': v for k, v in info.items()})
    with open(os.path.join(sd, 'config.py'), 'w') as f:
        f.write(_STAGE_CONFIG.format(name=os.path.basename(sd), m=m, base=os.path.basename(config_path),
                                     t_start=t_start, n_traj=q.size * n_spin, n_pts=q.size,
                                     n_spin=n_spin, seed=stage_seed(cfg.get('base_seed'), m, 0)))
    return sd


def _bins(cfg):
    b = cfg.get('bins')
    return None if b is None else (int(b[0]), int(b[1]))


def _resample(cfg, q, p, W, rng):
    return rs.resample(q, p, W, int(cfg['n_points']), bins=_bins(cfg),
                       sharing=cfg.get('sharing', 'shared'),
                       placement=cfg.get('placement', 'endpoint'), rng=rng)


def _print_info(info):
    print(f"[iter]   {info['n_endpoints']} weighted points on "
          + (f"{info['n_cells']} cells ({info['n_occupied']} occupied)" if info['gridded']
             else f"{info['n_cells']} distinct (q,p) (bins=None: no grid)")
          + f" -> {info['n_drawn']} draws at {info['n_distinct']} distinct (q,p)")
    print('[iter]   comp   sum|W| raw    sum|B| binned   sum W net      sum|w| drawn   sum w drawn')
    for k, c in enumerate(rs.COMPONENTS):
        print(f"[iter]   {c:>4s}  {info['raw_l1'][k]:13.6e} {info['binned_l1'][k]:13.6e} "
              f"{info['net'][k]:14.6e} {info['out_l1'][k]:13.6e} {info['out_net'][k]:14.6e}")


# ------------------------------------------------------------------ init
def cmd_init(config_path, force=False):
    cfg = load_config(config_path)
    run_dir = os.path.dirname(os.path.abspath(config_path))
    sd = stage_dir(run_dir, 0)
    if os.path.isfile(os.path.join(sd, 'init.npz')) and not force:
        raise FileExistsError(f'{sd}/init.npz exists (pass --force to redraw it)')
    if not cfg.get('shard_size'):
        raise ValueError('config needs shard_size: traj.py takes the trajectory index from the shard path')
    rng = np.random.default_rng(stage_seed(cfg.get('base_seed'), 0, 1))
    q0, p0, W0 = rs.sample_rho_init(cfg['rho_init'], int(cfg['n_pool_init']), rng)
    q, p, w, info = _resample(cfg, q0, p0, W0, rng)
    info['n_drawn'] = q.size
    write_stage(config_path, cfg, 0, q, p, w, info)
    print(f'[iter] stage 0: {q.size} points from rho_init -> {sd}')
    _print_info(info)
    return sd


# ------------------------------------------------------------------ resample
def _read_shard(fn):
    with h5py.File(fn, 'r') as f:
        idx = f['traj_index'][:]
        n = idx.size
        return (idx, f['time'][:], f['mapSx'][:n], f['mapSy'][:n], f['mapSz'][:n],
                f['nucR'][:n, :, :, 0], f['nucP'][:n, -1, :, 0])


def cmd_resample(config_path, m):
    cfg = load_config(config_path)
    run_dir = os.path.dirname(os.path.abspath(config_path))
    sd = stage_dir(run_dir, m)
    scfg = load_config(os.path.join(sd, 'config.py'))
    with np.load(os.path.join(sd, 'init.npz')) as z:
        q0, p0, w0 = z['q'], z['p'], z['w']
        n_spin = int(z['n_spin'])
    n_pts, n_traj = q0.size, int(scfg['n_traj'])
    idx_all = _committed(sd, scfg)
    if idx_all.size != n_traj or np.unique(idx_all).size != idx_all.size:
        raise RuntimeError(f'{sd}: {np.unique(idx_all).size} of {n_traj} trajectories committed; '
                           f'finish the stage first (rerun its runner / submit_grid.sh)')

    time = None
    acc = None
    qe, pe, We = [], [], []
    for fn in _shard_files(sd, scfg):
        idx, t, Sx, Sy, Sz, R, Pend = _read_shard(fn)
        if idx.size == 0:
            continue
        if time is None:
            time = t
            acc = np.zeros((n_pts, len(NAMES), t.size))
        elif not np.array_equal(t, time):
            raise ValueError(f'{fn}: time grid differs from the rest of the stage')
        i = idx // n_spin
        sx, sy, sg = Sx.mean(axis=-1), Sy.mean(axis=-1), np.sign(Sz).mean(axis=-1)
        aP, aC = rs.source_factors(w0[i], (sx[:, 0], sy[:, 0], sg[:, 0], Sz[:, 0].mean(axis=-1)))
        hg, he = rs.heaviside(-Sz), rs.heaviside(Sz)
        hl, hr = rs.heaviside(-R), rs.heaviside(R)
        a = aP[:, None] / n_spin
        Rg, Tg = a * (hl * hg).mean(-1), a * (hr * hg).mean(-1)
        Re, Te = a * (hl * he).mean(-1), a * (hr * he).mean(-1)
        X = 0.5 * aC[:, None] * sx / n_spin
        Y = 0.5 * aC[:, None] * sy / n_spin
        obs = np.stack([Rg, Tg, Re, Te, Rg + Tg, Re + Te, Rg + Tg + Re + Te, X, Y], axis=1)
        np.add.at(acc, i, obs)
        qe.append(R[:, -1].mean(axis=-1)); pe.append(Pend.mean(axis=-1))
        We.append(rs.endpoint_weights(aP, aC, (sx[:, -1], sy[:, -1], sg[:, -1]), n_spin))
    qe, pe, We = np.concatenate(qe), np.concatenate(pe), np.concatenate(We)

    tot = acc.sum(axis=0)
    se = np.sqrt(n_pts) * acc.std(axis=0, ddof=1) if n_pts > 1 else np.zeros_like(tot)
    # what the stage's zero-time row estimates: the init totals
    gI, gz, gx, gy = w0.T
    hl0, hr0 = rs.heaviside(-q0), rs.heaviside(q0)
    init_tot = np.array([((gI - gz) * hl0).sum(), ((gI - gz) * hr0).sum(), ((gI + gz) * hl0).sum(),
                         ((gI + gz) * hr0).sum(), (gI - gz).sum(), (gI + gz).sum(), 2 * gI.sum(),
                         gx.sum(), gy.sum()])

    t_start = float(scfg['t_start'])
    print(f'[iter] stage {m}: t {t_start:g} -> {time[-1]:g}, {n_pts} points x {n_spin} spins = '
          f'{n_traj} trajectories')
    print('[iter]          ' + ''.join(f'{k:>24s}' for k in NAMES))
    print('[iter]   init   ' + ''.join(f'{v:24.6e}' for v in init_tot))
    print('[iter]   t0 MC  ' + ''.join(f' {v:13.6e} +-{s:7.1e}' for v, s in zip(tot[:, 0], se[:, 0])))
    print('[iter]   end    ' + ''.join(f' {v:13.6e} +-{s:7.1e}' for v, s in zip(tot[:, -1], se[:, -1])))

    out = dict(time=time, names=np.array(NAMES), tot=tot, se=se, init_tot=init_tot, stage=m,
               t_start=t_start, n_points=n_pts, n_spin=n_spin, n_traj=n_traj,
               init_q=q0, init_p=p0, init_w=w0,
               end_net=We.sum(axis=0), end_l1=np.abs(We).sum(axis=0))
    if m + 1 < int(cfg['n_stages']):
        rng = np.random.default_rng(stage_seed(cfg.get('base_seed'), m + 1, 1))
        q, p, w, info = _resample(cfg, qe, pe, We, rng)
        info['n_drawn'] = q.size
        write_stage(config_path, cfg, m + 1, q, p, w, info)
        print(f'[iter] resampled stage {m} -> stage {m + 1} ({stage_dir(run_dir, m + 1)}):')
        _print_info(info)
        out.update({f'resample_{k}': v for k, v in info.items()})
    else:
        print(f'[iter] stage {m} is the last (n_stages = {cfg["n_stages"]}): no resampling')
    np.savez(os.path.join(sd, 'summary.npz'), **out)
    return out


# ------------------------------------------------------------------ local loop
def cmd_local(config_path, ncores=None):
    cfg = load_config(config_path)
    run_dir = os.path.dirname(os.path.abspath(config_path))
    if not os.path.isfile(os.path.join(stage_dir(run_dir, 0), 'init.npz')):
        cmd_init(config_path)
    for m in range(int(cfg['n_stages'])):
        sd = stage_dir(run_dir, m)
        scfg_path = os.path.join(sd, 'config.py')
        if not os.path.isfile(scfg_path):
            raise FileNotFoundError(f'{sd} missing: resample stage {m - 1} first')
        scfg = load_config(scfg_path)
        if not _complete(sd, scfg):
            print(f'[iter] running stage {m}: {scfg["n_traj"]} trajectories', flush=True)
            cmd = [sys.executable, '-m', 'workflow.runner', '--config', scfg_path]
            if ncores:
                cmd += ['--ncores', str(int(ncores))]
            subprocess.run(cmd, check=True)
        last = m + 1 >= int(cfg['n_stages'])
        if not os.path.isfile(os.path.join(sd, 'summary.npz')) or (
                not last and not os.path.isfile(os.path.join(stage_dir(run_dir, m + 1), 'init.npz'))):
            cmd_resample(config_path, m)
    print(f'[iter] all {cfg["n_stages"]} stages done')


# ------------------------------------------------------------------ SLURM chain
_RESAMPLE_SBATCH = """#!/bin/bash
#SBATCH --job-name={job_name}
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task={cpus}
#SBATCH --time={time}
#SBATCH --output={sd}/resample_%j.out
#SBATCH --error={sd}/resample_%j.err
{extra}
export OMP_NUM_THREADS=1
export OPENBLAS_NUM_THREADS=1
export MKL_NUM_THREADS=1

export PYTHONPATH={rp_mash_root}:$PYTHONPATH
cd {run_dir}
{extra_cmds}
set -e
# stage {m}'s trajectories -> summary + stage {m1}'s points, then chain the next stage
{python} {iterate} resample --config {config} --stage {m}
{next}
"""


def _write_resample_sbatch(config_path, cfg, m):
    import workflow
    run_dir = os.path.dirname(os.path.abspath(config_path))
    sd = stage_dir(run_dir, m)
    sl, rsl = cfg.get('slurm', {}), cfg.get('resample_slurm', {})
    extra = [f'#SBATCH --{k}={sl[k]}' for k in ('partition', 'account', 'qos') if sl.get(k)]
    mem = rsl.get('mem', sl.get('mem'))
    if mem:
        extra.append(f'#SBATCH --mem={mem}')
    extra += [d if d.startswith('#SBATCH') else f'#SBATCH {d}' for d in sl.get('extra_directives', [])]
    python = sl.get('python', 'python')
    iterate = os.path.abspath(__file__)
    config = os.path.abspath(config_path)
    nxt = (f'{python} {iterate} chain --config {config} --stage {m + 1}'
           if m + 1 < int(cfg['n_stages']) else f'echo "[iter] all {cfg["n_stages"]} stages done"')
    text = _RESAMPLE_SBATCH.format(
        job_name=f"{sl.get('job_name', 'rpmash')}_rs{m:02d}", cpus=int(rsl.get('cpus_per_task', 1)),
        time=rsl.get('time', '0:59:00'), sd=sd, extra='\n'.join(extra),
        rp_mash_root=os.path.dirname(os.path.dirname(os.path.abspath(workflow.__file__))),
        run_dir=run_dir, extra_cmds='\n'.join(sl.get('extra_commands', [])), m=m, m1=m + 1,
        python=python, iterate=iterate, config=config, next=nxt)
    path = os.path.join(sd, 'resample.sh')
    with open(path, 'w') as f:
        f.write(text)
    os.chmod(path, 0o755)
    return path


def _sbatch(args):
    r = subprocess.run(['sbatch'] + args, capture_output=True, text=True, check=True)
    return r.stdout.strip().split(';')[0]


def cmd_chain(config_path, m=0, dry_run=False):
    from workflow.slurm import write_array_sbatch
    cfg = load_config(config_path)
    run_dir = os.path.dirname(os.path.abspath(config_path))
    sd = stage_dir(run_dir, m)
    if not os.path.isfile(os.path.join(sd, 'init.npz')):
        if m != 0:
            raise FileNotFoundError(f'{sd} missing: resample stage {m - 1} first')
        cmd_init(config_path)
    grid = write_array_sbatch(os.path.join(sd, 'config.py'))
    res = _write_resample_sbatch(config_path, cfg, m)
    if dry_run:
        print(f'[iter] dry run, would submit:\n    sbatch --parsable {grid}\n'
              f'    sbatch --parsable --dependency=afterok:<array job> {res}')
        return None
    jid = _sbatch(['--parsable', grid])
    jid2 = _sbatch(['--parsable', f'--dependency=afterok:{jid}', res])
    print(f'[iter] stage {m}: trajectories job {jid}, resample job {jid2} (afterok:{jid})')
    return jid, jid2


# ------------------------------------------------------------------ status
def cmd_status(config_path):
    cfg = load_config(config_path)
    run_dir = os.path.dirname(os.path.abspath(config_path))
    for m in range(int(cfg['n_stages'])):
        sd = stage_dir(run_dir, m)
        if not os.path.isfile(os.path.join(sd, 'config.py')):
            print(f'[iter] stage {m}: not created')
            continue
        scfg = load_config(os.path.join(sd, 'config.py'))
        n = np.unique(_committed(sd, scfg)).size
        done = os.path.isfile(os.path.join(sd, 'summary.npz'))
        print(f"[iter] stage {m}: {n}/{scfg['n_traj']} trajectories, "
              + ('summary.npz written' if done else 'no summary yet'))


def _main():
    ap = argparse.ArgumentParser(description='Stages of MASH-RPMD_Tully-Testing.')
    ap.add_argument('command', choices=('init', 'resample', 'local', 'chain', 'status'))
    ap.add_argument('--config', default='config.py')
    ap.add_argument('--stage', type=int, default=0)
    ap.add_argument('--ncores', type=int, default=None)
    ap.add_argument('--force', action='store_true', help='init: redraw stage_00 points')
    ap.add_argument('--dry-run', action='store_true', help='chain: write the scripts, submit nothing')
    a = ap.parse_args()
    if a.command == 'init':
        cmd_init(a.config, force=a.force)
    elif a.command == 'resample':
        cmd_resample(a.config, a.stage)
    elif a.command == 'local':
        cmd_local(a.config, ncores=a.ncores)
    elif a.command == 'chain':
        cmd_chain(a.config, a.stage, dry_run=a.dry_run)
    else:
        cmd_status(a.config)


if __name__ == '__main__':
    _main()
