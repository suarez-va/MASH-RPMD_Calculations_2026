"""
traj.py -- the ONLY stage for the Tully single-avoided-crossing grid.

Unlike MASH-RPMD_System-Bath, there is no thermalization stage and no thermostat.  The System-Bath
workflow needs one because its trajectories start from an NVT ensemble that has to be generated by
a GLE burn-in (therm.py) and handed over through therm_<idx>.hdf.  A Tully scattering problem has
no such ensemble: every trajectory is a wavepacket sample prepared analytically at t=0, so the
initial conditions are drawn right here and the trajectory is propagated microcanonically.

Initial conditions follow RP_MASH/example_scripts/run_mashrpmd.py:

    nucR ~ Normal( nucR_init, sqrt(1/(2*ga)) )     one draw per bead
    nucP  = nucP_init                              the same incident momentum for every bead

i.e. a Gaussian wavepacket of width `ga` centred at `nucR_init`, launched at fixed momentum toward
the avoided crossing at R = 0.  (The example also has a commented-out Gaussian draw for nucP; the
deterministic form is the one it actually uses, and is what is reproduced here.)

workflow.worker chdirs into traj_grid/traj<idx>/ and calls run_trajectory(cfg, seed), so every
output file lands in that trajectory's own directory.

    python -m workflow.runner --config config.py                        # local
    python -m workflow.slurm  --config config.py && sbatch submit_grid.sh  # cluster
"""

import numpy as np
import mash_rpmd   # via PYTHONPATH (= /home/victorwsl/repos/RP_MASH)


def _seeds(seed):
    """
    Split the one trajectory seed into (initial conditions, dynamics).

    The initial-condition draw here and the RNG streams inside mash_rpmd must not be the same
    stream, or the wavepacket sample and the spin/jump sampling would be correlated.  mash_rpmd
    builds its own SeedSequence from whatever integer it is given, so handing it a sibling of this
    module's stream keeps the two independent while leaving the whole trajectory reproducible from
    `base_seed`.  seed=None -> both fall back to OS entropy, exactly as before.
    """
    if seed is None:
        return None, None
    ic, dyn = np.random.SeedSequence(int(seed)).generate_state(2, dtype=np.uint32)
    return int(ic), int(dyn)


def run_trajectory(cfg, seed):
    ic_seed, dyn_seed = _seeds(seed)
    rng = np.random.default_rng(ic_seed)

    nbds, nnuc = int(cfg['nbds']), int(cfg['nnuc'])

    # ---- wavepacket sample at t=0 ----
    nucR = rng.normal(cfg['nucR_init'], np.sqrt(1.0 / (2.0 * cfg['ga'])), (nbds, nnuc))
    nucP = rng.normal(cfg['nucP_init'], np.sqrt(cfg['ga'] / 2.0), (nbds, nnuc))
    #nucP = cfg['nucP_init'] * np.ones((nbds, nnuc))

    # tully_1ac wants each parameter as its own (nnuc,) array -- see potential.tully_1ac.error_check
    potparams = [np.array([cfg['A']]), np.array([cfg['B']]),
                 np.array([cfg['C']]), np.array([cfg['D']])]

    # No langevin/langevin_params: mash_rpmd defaults langevin=None, which switches off every GLE
    # branch in the integrator (and with it the per-trajectory memK.dat that the System-Bath driver
    # has to delete afterwards).
    m = mash_rpmd.mash_rpmd(
        nstates=cfg['nstates'], nnuc=nnuc, nbds=nbds,
        beta=cfg['beta'], mass=np.asarray(cfg['mass'], float),
        potype='tully_1ac', potparams=potparams, nucR=nucR, nucP=nucP,
        spinmap_bool=True, centroid_bool=True, bead_bool=False,
        Tjump=cfg['Tjump'], full_jump=cfg['full_jump'], seed=dyn_seed)

    # init_state=0 -> cos(theta) drawn from (-1, 0): the particle starts on the LOWER adiabat,
    # matching run_mashrpmd.py.  (System-Bath uses init_state=None because it samples the whole
    # sphere for its equilibrium correlation function; a scattering problem has a definite entrance
    # channel.)
    m.init_map_spin(0)

    Nprod = round(cfg['traj_time'] / cfg['delt'])
    m.run_dynamics(Nprod, cfg['Nprint'], cfg['delt'], cfg['intype'],
                   init_time=0.0, small_dt_ratio=1)
